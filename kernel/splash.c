#include "splash.h"
#include "vga.h"

static const char *const splash_logo[] = {
    "\xDB\xDB\xDB\xDB\xDB \xDB\xDB\xDB\xDB\xDB \xDB\xDB\xDB\xDB\xDB  \xDB\xDB\xDB\xDB  \xDB\xDB\xDB   \xDB\xDB\xDB\xDB",
    "\xDB     \xDB     \xDB     \xDB     \xDB   \xDB \xDB    ",
    "\xDB\xDB\xDB\xDB  \xDB\xDB\xDB\xDB  \xDB\xDB\xDB\xDB   \xDB\xDB\xDB  \xDB   \xDB  \xDB\xDB\xDB ",
    "\xDB     \xDB     \xDB         \xDB \xDB   \xDB     \xDB",
    "\xDB\xDB\xDB\xDB\xDB \xDB     \xDB\xDB\xDB\xDB\xDB \xDB\xDB\xDB\xDB   \xDB\xDB\xDB  \xDB\xDB\xDB\xDB "
};

void splash_show(void)
{
    unsigned int row;

    for (row = 0; row < sizeof(splash_logo) / sizeof(splash_logo[0]); row++) {
        vga_write(splash_logo[row]);
        vga_write_char('\n');
    }

    vga_write_char('\n');
}
